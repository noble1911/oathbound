// Regenerates tools/review/botx.ts, the review copy of src/sim/bot.ts: the same code with internals exported and a few
// knobs (KNOB) the experiment scripts flip. Run it whenever bot.ts changes:   node tools/review/mkbotx.ts
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../../src/sim/bot.ts', import.meta.url);
const out = new URL('./botx.ts', import.meta.url);
let s = readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
const swap = (from: string, to: string): void => {
  if (!s.includes(from)) throw new Error(`mkbotx: bot.ts no longer contains ${JSON.stringify(from)}; update this script`);
  s = s.split(from).join(to);
};
s = '// REVIEW COPY of src/sim/bot.ts (docs/reviews/POSITIONING-AND-ECONOMY.md) with internals exported and knobs. Not used by the game.\n'
  + '// Generated by tools/review/mkbotx.ts: do not edit, regenerate it.\n' + s;
s = s.replace(/from '\.\//g, "from '../../src/sim/");
for (const fn of ['placeFor', 'threatsOf', 'hardLayout', 'applyLayout']) swap(`\nfunction ${fn}(`, `\nexport function ${fn}(`);
swap('const HARD_LEVEL_BIAS = ', 'const HARD_LEVEL_BIAS_SHIPPED = ');
swap('\nfunction planHard(', '\nexport const KNOB = { noLevel: false, noLayout: false, bias: HARD_LEVEL_BIAS_SHIPPED, sync: HARD_SPEED_SYNC, from: HARD_LEVEL_FROM };\nfunction planHard(');
swap('lv.w * HARD_LEVEL_BIAS > bw', 'lv.w * KNOB.bias > bw');
swap('const lv = s.round < HARD_LEVEL_FROM ? null : hardLevelPick(s, seat, threats, salt, hold);', 'const lv = KNOB.noLevel || s.round < KNOB.from ? null : hardLevelPick(s, seat, threats, salt, hold);');
swap('\n  applyLayout(s, seat, hardLayout(p, threats', '\n  if (!KNOB.noLayout) applyLayout(s, seat, hardLayout(p, threats');
swap('if (HARD_SPEED_SYNC) speedStagger', 'if (KNOB.sync) speedStagger');
writeFileSync(out, s);
console.log('tools/review/botx.ts regenerated from src/sim/bot.ts');
